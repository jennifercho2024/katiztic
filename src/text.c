/* text.c — see text.h. The glyph table and the code that stamps it out.
 *
 * Each glyph is 6 rows of 4 bits, stored one hex digit per row (0x0..0xF).
 * A row's four pixels are bits 3..0: leftmost pixel is bit 3 (0x8), rightmost
 * is bit 0 (0x1). So 0x6 = 0110 = ".##." — you can read the shapes in the
 * table if you think in nibbles. 1 = lit pixel, 0 = blank.
 */
#include "text.h"
#include "render.h"
#include <string.h>

/* Rows use only the low 4 bits. nibble maps left..right. */
typedef struct { Uint8 row[KZ_GLYPH_H]; } Glyph;

/* Blank glyph (space / unknown). */
#define BLANK { {0,0,0,0,0,0} }

