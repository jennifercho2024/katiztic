/* Punctuation we actually use. */
static const Glyph G_SPACE  = BLANK;
static const Glyph G_EXCL   = {{0x4,0x4,0x4,0x4,0x0,0x4}}; /* ! */
static const Glyph G_PERIOD = {{0x0,0x0,0x0,0x0,0x0,0x4}}; /* . */
static const Glyph G_COMMA  = {{0x0,0x0,0x0,0x0,0x4,0x8}}; /* , */
static const Glyph G_COLON  = {{0x0,0x4,0x0,0x0,0x4,0x0}}; /* : */
static const Glyph G_QUEST  = {{0x6,0x9,0x2,0x4,0x0,0x4}}; /* ? */
static const Glyph G_APOS   = {{0x4,0x4,0x0,0x0,0x0,0x0}}; /* ' */
static const Glyph G_HYPHEN = {{0x0,0x0,0x0,0xF,0x0,0x0}}; /* - */

/* Resolve an ASCII character to its glyph. Unknowns become blank. */
static const Glyph *glyph_for(char ch) {
    if (ch >= '0' && ch <= '9') return &G_DIGIT[ch - '0'];
    if (ch >= 'A' && ch <= 'Z') return &G_UPPER[ch - 'A'];
    if (ch >= 'a' && ch <= 'z') return &G_LOWER[ch - 'a'];
    switch (ch) {
        case ' ': return &G_SPACE;
        case '!': return &G_EXCL;
        case '.': return &G_PERIOD;
        case ',': return &G_COMMA;
        case ':': return &G_COLON;
        case '?': return &G_QUEST;
        case '\'': return &G_APOS;
        case '-': return &G_HYPHEN;
        default:  return &G_SPACE;
    }
}

float text_draw(SDL_Renderer *r, const char *s, float x, float y, Color c) {
    float pen = x;
    for (const char *p = s; *p; p++) {
        const Glyph *g = glyph_for(*p);
        for (int row = 0; row < KZ_GLYPH_H; row++) {
            Uint8 bits = g->row[row];
            for (int col = 0; col < KZ_GLYPH_W; col++) {
                if (bits & (0x8 >> col)) {
                    px_rect(r, pen + col, y + row, 1, 1, c);
                }
            }
        }
        pen += KZ_CHAR_ADVANCE;
    }
    return pen - x;
}

float text_width(const char *s) {
    return (float)((int)strlen(s) * KZ_CHAR_ADVANCE);
}

/* Draw text at an integer scale (2 = double size, etc). Each glyph pixel
 * becomes a scale×scale block. Returns the advance width in pixels. */
float text_draw_scaled(SDL_Renderer *r, const char *s, float x, float y,
                       Color c, int scale) {
    if (scale < 1) scale = 1;
    float pen = x;
    for (const char *p = s; *p; p++) {
        const Glyph *g = glyph_for(*p);
        for (int row = 0; row < KZ_GLYPH_H; row++) {
            Uint8 bits = g->row[row];
            for (int col = 0; col < KZ_GLYPH_W; col++) {
                if (bits & (0x8 >> col)) {
                    px_rect(r, pen + col * scale, y + row * scale,
                            (float)scale, (float)scale, c);
                }
            }
        }
        pen += (float)(KZ_CHAR_ADVANCE * scale);
    }
    return pen - x;
}

float text_width_scaled(const char *s, int scale) {
    if (scale < 1) scale = 1;
    return (float)((int)strlen(s) * KZ_CHAR_ADVANCE * scale);
}

void text_draw_centered(SDL_Renderer *r, const char *s, float cx, float y,
                        Color c) {
    text_draw(r, s, cx - text_width(s) / 2.0f, y, c);
}